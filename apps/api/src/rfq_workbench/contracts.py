"""Versioned domain contracts shared by the API, workflow, and acceptance tools.

Money crosses the API as decimal strings. Evidence identifiers are generated by
the parser; model output may reference them, but cannot create approval events.
"""

from datetime import date, datetime
from decimal import Decimal
from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class Contract(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)


class RunState(StrEnum):
    RECEIVED = "RECEIVED"
    EXTRACTING = "EXTRACTING"
    VALIDATING = "VALIDATING"
    NEEDS_ENGINEERING_REVIEW = "NEEDS_ENGINEERING_REVIEW"
    READY_FOR_APPROVAL = "READY_FOR_APPROVAL"
    APPROVED_DRAFT = "APPROVED_DRAFT"
    EXPORTED_DRAFT = "EXPORTED_DRAFT"
    FAILED_RETRYABLE = "FAILED_RETRYABLE"
    FAILED_FINAL = "FAILED_FINAL"


class ConfirmedInputs(Contract):
    """Explicitly confirmed M1 input; not a substitute for M2 file extraction."""

    part_number: str = Field(min_length=1, max_length=80)
    required_revision: str = Field(min_length=1, max_length=16)
    drawing_revision: str = Field(min_length=1, max_length=16)
    quantity: int = Field(strict=True, gt=0, le=100_000)
    material: str = Field(min_length=1, max_length=80)
    unit: str = "mm"
    currency: str = "EUR"
    plant: str = "DE-DEMO"
    product_family: str = "mounting-bracket"


class Source(Contract):
    id: str
    document_id: str
    page: int = Field(ge=1)
    text: str
    bbox: list[float] | None = None
    locator: Literal["text", "page"] = "text"

    @model_validator(mode="after")
    def valid_box(self):
        if self.bbox is not None:
            if len(self.bbox) != 4 or not all(0 <= n <= 1 for n in self.bbox):
                raise ValueError("bbox must contain four normalized coordinates")
            if self.bbox[0] >= self.bbox[2] or self.bbox[1] >= self.bbox[3]:
                raise ValueError("bbox must have positive area")
        return self


class ExtractedValue(Contract):
    value: str | None = Field(max_length=200)
    source_id: str | None = Field(max_length=150)

    @field_validator("value", "source_id", mode="before")
    @classmethod
    def normalize_unknown(cls, value):
        if isinstance(value, str):
            value = value.strip()
            if value.casefold() in {
                "",
                "unknown",
                "null",
                "n/a",
                "tbd",
                "not provided",
                "[not provided]",
                "未知",
                "未提供",
            }:
                return None
        return value


class EvidenceCheck(Contract):
    status: Literal[
        "MISSING", "INVALID_SOURCE", "TEXT_VERIFIED", "TEXT_MISMATCH", "AMBIGUOUS", "VISUAL_REVIEW"
    ]
    source_exists: bool
    value_supported: bool
    locator: Literal["text", "page"] | None
    message: str


class ReviewedField(ExtractedValue):
    original_value: str | None
    source_valid: bool
    needs_visual_review: bool
    human_confirmed: bool
    evidence: EvidenceCheck


class DrawingExtraction(Contract):
    part_number: ExtractedValue
    revision: ExtractedValue
    material: ExtractedValue
    unit: ExtractedValue
    width_mm: ExtractedValue
    height_mm: ExtractedValue
