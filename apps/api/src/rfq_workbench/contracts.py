class Issue(Contract):
    code: str
    field: str
    message: str
    severity: Literal["blocking", "warning"] = "blocking"


class CostLine(Contract):
    code: str
    description: str
    unit_cost: Decimal
    batch_cost: Decimal
    basis: str


class Quote(Contract):
    draft_version: int
    quantity: int
    currency: Literal["EUR"] = "EUR"
    unit_cost: Decimal
    unit_price: Decimal
    total_price: Decimal
    margin: Decimal
    lines: list[CostLine]
    input_hash: str
    reference_hash: str
    rules_version: str
