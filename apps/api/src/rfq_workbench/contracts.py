"""Versioned domain contracts shared by the API, workflow, and acceptance tools.

Money crosses the API as decimal strings. Evidence identifiers are generated by
the parser; model output may reference them, but cannot create approval events.
"""

from datetime import datetime
from decimal import Decimal
from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class Contract(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)


class RunState(StrEnum):
    RECEIVED = "RECEIVED"
    EXTRACTING = "EXTRACTING"
    VALIDATING = "VALIDATING"
    NEEDS_ENGINEERING_REVIEW = "NEEDS_ENGINEERING_REVIEW"
    READY_FOR_APPROVAL = "READY_FOR_APPROVAL"
    APPROVED_DRAFT = "APPROVED_DRAFT"
    EXPORTED_DRAFT = "EXPORTED_DRAFT"
    FAILED_RETRYABLE = "FAILED_RETRYABLE"
    FAILED_FINAL = "FAILED_FINAL"


class ConfirmedInputs(Contract):
    """Explicitly confirmed M1 input; not a substitute for M2 file extraction."""

    part_number: str = Field(min_length=1, max_length=80)
    required_revision: str = Field(min_length=1, max_length=16)
    drawing_revision: str = Field(min_length=1, max_length=16)
    quantity: int = Field(strict=True, gt=0, le=100_000)
    material: str = Field(min_length=1, max_length=80)
    unit: str = "mm"
    currency: str = "EUR"
    plant: str = "DE-DEMO"
    product_family: str = "mounting-bracket"


class Source(Contract):
    id: str
    document_id: str
    page: int = Field(ge=1)
    text: str
    bbox: list[float] | None = None
    locator: Literal["text", "page"] = "text"


class ExtractedValue(Contract):
    value: str | None
    source_id: str | None


class DrawingExtraction(Contract):
    part_number: ExtractedValue
    revision: ExtractedValue
    material: ExtractedValue
    unit: ExtractedValue
    width_mm: ExtractedValue
    height_mm: ExtractedValue
    thickness_mm: ExtractedValue
    hole_diameter_mm: ExtractedValue
    surface_finish: ExtractedValue


class RfqExtraction(Contract):
    part_number: ExtractedValue
    required_revision: ExtractedValue
    quantity: ExtractedValue
    currency: ExtractedValue


class Extraction(Contract):
    rfq: RfqExtraction
    drawing: DrawingExtraction


class Issue(Contract):
    code: str
    field: str
    message: str
    severity: Literal["blocking", "warning"] = "blocking"


class CostLine(Contract):
    code: str
    description: str
    unit_cost: Decimal
    batch_cost: Decimal
    basis: str


class Quote(Contract):
    draft_version: int
    quantity: int
    currency: Literal["EUR"] = "EUR"
    unit_cost: Decimal
    unit_price: Decimal
    total_price: Decimal
    margin: Decimal
    lines: list[CostLine]
    input_hash: str
    reference_hash: str
    rules_version: str
    rate_version: str
    template_version: str
    pending: list[str]


class AuditEvent(Contract):
    sequence: int
    occurred_at: datetime
    actor: str
    action: str
    detail: dict


class Mutation(Contract):
    expected_version: int = Field(ge=1)


class ChangeInputs(Mutation):
    inputs: ConfirmedInputs
    reason: str = Field(min_length=3, max_length=1000)


class ApproveRequest(Mutation):
    technical_confirmed: Literal[True]
    internal_only: Literal[True]
    note: str = Field(min_length=3, max_length=1000)


class CorrectFields(Mutation):
    values: dict[str, str]
    reason: str = Field(min_length=3, max_length=1000)


class AnalyzeRequest(Mutation):
    mode: Literal["local_text", "live"] = "local_text"
