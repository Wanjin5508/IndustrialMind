class KnowledgeRecord(Contract):
    id: str = Field(min_length=1, max_length=80)
    title: str
    kind: Literal["catalog", "template", "rate", "history"]
    project_id: str
    plant: str
    product_family: str
    roles: list[Literal["demo-engineer", "demo-approver"]] = Field(min_length=1)
    part_number: str
    material: str
    unit: str
    currency: str
    revisions: list[str] = Field(min_length=1)
    approved: bool = Field(strict=True)
    valid_from: date
    valid_until: date
    version: str
    content: str
    origin_type: Literal["synthetic"]
    payload_source: Literal["manufacturing", "reference_only"]


class KnowledgeQuery(Contract):
    query: str = Field(default="", max_length=200)
    part_number: str = Field(default="PM-BRKT-010", max_length=80)
    material: str = Field(default="Al-6061-T6", max_length=80)
    unit: str = Field(default="mm", max_length=16)
    currency: str = Field(default="EUR", max_length=16)
    revision: str = Field(default="B", max_length=16)
    kind: Literal["catalog", "template", "rate", "history"] | None = None


class AuditEvent(Contract):
    sequence: int
    occurred_at: datetime
    actor: str
    action: str
    detail: dict


class Mutation(Contract):
    expected_version: int = Field(ge=1)


class ChangeInputs(Mutation):
    inputs: ConfirmedInputs
    reason: str = Field(min_length=3, max_length=1000)


class ApproveRequest(Mutation):
    technical_confirmed: Literal[True]
    internal_only: Literal[True]
    note: str = Field(min_length=3, max_length=1000)


class CorrectFields(Mutation):
    values: dict[str, str]
    reason: str = Field(min_length=3, max_length=1000)


class AnalyzeRequest(Mutation):
    mode: Literal["local_text", "live"] = "local_text"
